// 只匹配完整合法坐标；打开旧设置时不能将未配置值识别为某个预设。
function findCity(cities, latitude, longitude) {
    if (typeof latitude !== "number" || typeof longitude !== "number"
            || !isFinite(latitude) || !isFinite(longitude)) return -1
    for (var i = 0; i < cities.length; ++i)
        if (Math.abs(cities[i].latitude - latitude) < 0.000001
                && Math.abs(cities[i].longitude - longitude) < 0.000001) return i
    return -1
}
